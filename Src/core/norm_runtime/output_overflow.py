"""Lossless runtime output receipts and durable originals (0.55.8 r5).

Only generated bytes are retained; output lost to a model token limit cannot be
recreated from Redis. Never convert a partial model result into an N1 acceptance.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re
import uuid


@dataclass(frozen=True)
class OverflowReceipt:
    key: str
    characters: int
    handoff: str


class OverflowStore:
    def __init__(self, redis_client, *, ttl_seconds: int = 86400):
        self.redis = redis_client
        self.ttl_seconds = max(60, int(ttl_seconds))

    def save(self, task_id: str, step_id: str, stage: str, text: str) -> OverflowReceipt:
        content = str(text or "")
        safe = lambda v: re.sub(r"[^A-Za-z0-9_.-]+", "_", str(v))[:80] or "unknown"
        key = f"norm:output:overflow:{safe(task_id)}:{safe(step_id)}:{safe(stage)}:{uuid.uuid4().hex}"
        self.redis.setex(key, self.ttl_seconds, content.encode("utf-8"))
        # Verify payload round-trip before giving another model a reference.
        received = self.redis.get(key)
        if received is None or (received.decode("utf-8") if isinstance(received, bytes) else str(received)) != content:
            raise RuntimeError("Redis output overflow preservation failed readback verification")
        preview = content[:2200]
        handoff = (
            f"GENERATED OUTPUT PREFIX ({len(preview)} of {len(content)} chars; generation may be incomplete):\n"
            f"{preview}\n\nFULL GENERATED TEXT IN REDIS: key={key} "
            f"(UTF-8 string, TTL={self.ttl_seconds}s). The runtime must retrieve the remainder "
            "before treating this as a complete submission. Do not pretend ungenerated text exists."
        )
        return OverflowReceipt(key=key, characters=len(content), handoff=handoff)

    def load(self, key: str) -> str:
        if not str(key).startswith("norm:output:overflow:"):
            raise ValueError("not an output-overflow Redis reference")
        content = self.redis.get(key)
        if content is None:
            raise FileNotFoundError("overflow working copy expired from Redis")
        return content.decode("utf-8") if isinstance(content, bytes) else str(content)


def write_full_report(state_root: Path, task_id: str, step_id: str, text: str) -> Path:
    root = Path(state_root) / "reports" / "final-overflow"
    root.mkdir(parents=True, exist_ok=True)
    safe = lambda v: re.sub(r"[^A-Za-z0-9_.-]+", "_", str(v))[:80] or "unknown"
    path = root / f"{safe(task_id)}-{safe(step_id)}-{uuid.uuid4().hex[:12]}.md"
    # Unique names, exclusive creation, never overwrite a previously preserved answer.
    with path.open("x", encoding="utf-8", newline="\n") as stream:
        stream.write(str(text or ""))
    return path


def report_link(path: Path) -> str:
    # Windows/Unix filesystem URI points to the user's locally stored original.
    return f"[full original Markdown]({Path(path).resolve().as_uri()}) (`{path}`)"
